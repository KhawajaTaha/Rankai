import Link from "next/link";
import { ArrowRight, Brain, CheckCircle2, Circle, Pin, Sparkles } from "lucide-react";
import { requireStaff } from "@/lib/auth";
import { db } from "@/lib/db";
import { getAccessibleClient } from "@/lib/tenancy";
import { modes } from "@/lib/env";
import { refreshOnboarding, onboardingProgress } from "@/lib/services/onboarding";
import { ACTIONS } from "@/lib/engine/risk";
import { addDays, fmtNum } from "@/lib/utils";
import { Badge, Card, EmptyState, LineChart, Progress, Stat, severityTone, timeAgo } from "@/components/ui";
import { ActionButton } from "@/components/client";
import { AssistantPanel } from "@/components/assistant";
import { clientAssistantAction, toggleChecklistAction } from "@/app/actions/clients";
import { STAGE_LABEL } from "@/lib/labels";

export default async function ClientOverview({ params }: { params: Promise<{ id: string }> }) {
  const ctx = await requireStaff();
  const { id } = await params;
  const client = await getAccessibleClient(ctx, id);
  const since30 = addDays(new Date(), -30);
  const since60 = addDays(new Date(), -60);
  const [{ next }, strategy, recs, checklist, metrics, prevMetrics, ga, activity, notes, gbpSeries] = await Promise.all([
    refreshOnboarding(id),
    db.weeklyStrategy.findFirst({ where: { clientId: id }, orderBy: { weekOf: "desc" } }),
    db.aiRecommendation.findMany({ where: { clientId: id, status: { in: ["PROPOSED", "NEEDS_APPROVAL", "SCHEDULED"] } }, orderBy: [{ severity: "asc" }, { confidence: "desc" }], take: 6 }),
    db.onboardingChecklistItem.findMany({ where: { clientId: id }, orderBy: { sortOrder: "asc" } }),
    db.gbpMetric.aggregate({ where: { clientId: id, date: { gte: since30 } }, _sum: { impressionsMaps: true, impressionsSearch: true, calls: true, websiteClicks: true, directionRequests: true } }),
    db.gbpMetric.aggregate({ where: { clientId: id, date: { gte: since60, lt: since30 } }, _sum: { impressionsMaps: true, impressionsSearch: true, calls: true, websiteClicks: true } }),
    db.ga4Metric.aggregate({ where: { clientId: id, date: { gte: since30 } }, _sum: { organicUsers: true, leads: true } }),
    db.activityLog.findMany({ where: { clientId: id }, orderBy: { createdAt: "desc" }, take: 8 }),
    db.supportNote.findMany({ where: { clientId: id, pinned: true }, orderBy: { createdAt: "desc" }, take: 3 }),
    db.gbpMetric.findMany({ where: { clientId: id, date: { gte: since30 } }, orderBy: { date: "asc" } }),
  ]);
  const views = (metrics._sum.impressionsMaps ?? 0) + (metrics._sum.impressionsSearch ?? 0);
  const prevViews = (prevMetrics._sum.impressionsMaps ?? 0) + (prevMetrics._sum.impressionsSearch ?? 0);
  const pct = (a: number, b: number) => (b ? ((a - b) / b) * 100 : null);
  const done = checklist.filter((c) => c.complete).length;
  const progress = client.status === "ONBOARDING" ? onboardingProgress(client.onboardingStage) : 100;

  return (
    <div className="grid gap-5 xl:grid-cols-3">
      <div className="space-y-5 xl:col-span-2">
        <div className="card flex flex-col gap-4 p-5 sm:flex-row sm:items-center">
          <div className="flex-1">
            <div className="text-xs font-semibold uppercase tracking-wide text-ink-500">Next recommended action</div>
            <div className="mt-1 text-base font-semibold text-ink-900">{next.label}</div>
            {client.status === "ONBOARDING" && (
              <div className="mt-2 flex items-center gap-3">
                <Progress value={progress} className="max-w-xs" />
                <span className="text-xs text-ink-500">Onboarding {progress}% · {STAGE_LABEL[client.onboardingStage]}</span>
              </div>
            )}
          </div>
          <Link href={next.href} className="btn-primary">{next.cta} <ArrowRight className="h-4 w-4" /></Link>
        </div>

        <div className="grid grid-cols-2 gap-3 md:grid-cols-4">
          <Stat label="GBP views (30d)" value={fmtNum(views)} delta={pct(views, prevViews)} />
          <Stat label="Calls from GBP" value={fmtNum(metrics._sum.calls ?? 0)} delta={pct(metrics._sum.calls ?? 0, prevMetrics._sum.calls ?? 0)} />
          <Stat label="Website clicks" value={fmtNum(metrics._sum.websiteClicks ?? 0)} delta={pct(metrics._sum.websiteClicks ?? 0, prevMetrics._sum.websiteClicks ?? 0)} />
          <Stat label="Organic users (30d)" value={fmtNum(ga._sum.organicUsers ?? 0)} hint={`${fmtNum(ga._sum.leads ?? 0)} leads`} />
        </div>

        <Card title="This week's SEO plan" subtitle={strategy ? `Week of ${strategy.weekOf.toLocaleDateString("en-CA", { month: "short", day: "numeric" })} · generated by ${strategy.generatedBy === "AI" ? "AI" : "Autopilot rules engine"}` : undefined} actions={<Sparkles className="h-4 w-4 text-brand-500" />}>
          {strategy ? (
            <>
              <p className="mb-4 text-sm text-ink-700">{strategy.summary}</p>
              <ol className="space-y-3">
                {(strategy.priorities as { rank: number; title: string; why: string; expectedImpact: string; risk: string; mode: string }[]).map((p) => (
                  <li key={p.rank} className="flex gap-3">
                    <span className="mt-0.5 inline-flex h-6 w-6 shrink-0 items-center justify-center rounded-full bg-brand-50 text-xs font-semibold text-brand-700">{p.rank}</span>
                    <div className="min-w-0 flex-1">
                      <div className="flex flex-wrap items-center gap-2">
                        <span className="text-sm font-medium text-ink-900">{p.title}</span>
                        <Badge tone={p.mode === "AUTO" ? "green" : p.mode === "APPROVAL" ? "amber" : "gray"}>{p.mode === "AUTO" ? "Auto" : p.mode === "APPROVAL" ? "Approval" : "Manual"}</Badge>
                        <Badge tone={severityTone(p.risk)}>{p.risk.toLowerCase()} risk</Badge>
                      </div>
                      <p className="text-xs text-ink-500">{p.why} · <span className="text-ink-600">Impact: {p.expectedImpact}</span></p>
                    </div>
                  </li>
                ))}
              </ol>
            </>
          ) : <EmptyState title="No plan yet" description="The weekly strategy is generated automatically once audits complete." />}
        </Card>

        <Card title="GBP visibility (30 days)" pad>
          <LineChart series={[{ name: "Maps", values: gbpSeries.map((m) => m.impressionsMaps) }, { name: "Search", values: gbpSeries.map((m) => m.impressionsSearch) }]} labels={gbpSeries.map((m) => m.date.toISOString().slice(5, 10))} />
        </Card>

        <Card title="Open recommendations" actions={<Link href={`/clients/${id}/automations`} className="link text-xs">All</Link>} pad={false}>
          {recs.length ? (
            <ul className="divide-y divide-ink-100">
              {recs.map((r) => (
                <li key={r.id} className="px-5 py-3">
                  <div className="flex flex-wrap items-center gap-2">
                    <span className="text-sm font-medium text-ink-900">{r.title}</span>
                    <Badge tone={r.actionClass === "AUTO_SAFE" ? "green" : r.actionClass === "PROTECTED" ? "red" : "amber"}>{r.actionClass.replace("_", "-").toLowerCase()}</Badge>
                    <Badge tone="gray">{Math.round(r.confidence * 100)}% confidence</Badge>
                    <Badge tone={r.status === "SCHEDULED" ? "blue" : r.status === "NEEDS_APPROVAL" ? "amber" : "gray"}>{r.status.replace("_", " ").toLowerCase()}</Badge>
                  </div>
                  <p className="mt-0.5 text-xs text-ink-500">{r.reason} {r.blockedReason && r.status !== "SCHEDULED" && <span className="text-ink-400">· {r.blockedReason}</span>}</p>
                  <div className="mt-1 text-[11px] text-ink-400">{ACTIONS[r.action]?.label} · signals: {r.sourceSignals.join(", ")}</div>
                </li>
              ))}
            </ul>
          ) : <EmptyState icon={<CheckCircle2 className="h-5 w-5" />} title="No open recommendations" />}
        </Card>
      </div>

      <div className="space-y-5">
        <Card title="Ask about this client" subtitle="Uses only this client's authorised data" actions={<Brain className="h-4 w-4 text-brand-500" />}>
          <AssistantPanel
            action={clientAssistantAction.bind(null, id)}
            mode={modes.aiLive() ? "LIVE" : "DEMO"}
            placeholder="Ask anything about this client…"
            suggestions={["What should we focus on this week?", "Why did rankings drop?", "Create next month's content plan.", "What did support discuss with this client?", "Which services need more promotion?", "What SEO work was completed this month?"]}
          />
        </Card>

        {notes.length > 0 && (
          <Card title="Pinned notes">
            <ul className="space-y-3">
              {notes.map((n) => <li key={n.id} className="flex gap-2 text-sm"><Pin className="mt-0.5 h-3.5 w-3.5 shrink-0 text-amber-500" /><span className="text-ink-700">{n.body}</span></li>)}
            </ul>
          </Card>
        )}

        <Card title="Onboarding checklist" subtitle={`${done}/${checklist.length} complete`}>
          <Progress value={(done / Math.max(1, checklist.length)) * 100} tone={done === checklist.length ? "green" : "brand"} className="mb-3" />
          <ul className="grid grid-cols-1 gap-1.5 sm:grid-cols-2 xl:grid-cols-1 2xl:grid-cols-2">
            {checklist.map((c) => (
              <li key={c.id}>
                <ActionButton action={toggleChecklistAction.bind(null, c.id)} className={`flex w-full items-center gap-2 rounded-lg px-2 py-1 text-left text-xs ${c.complete ? "text-ink-500 line-through" : "font-medium text-ink-800 hover:bg-ink-50"}`}>
                  {c.complete ? <CheckCircle2 className="h-3.5 w-3.5 text-emerald-500" /> : <Circle className="h-3.5 w-3.5 text-amber-500" />}{c.label}
                </ActionButton>
              </li>
            ))}
          </ul>
        </Card>

        <Card title="Recent activity" actions={<Link href={`/clients/${id}/activity`} className="link text-xs">Timeline</Link>} pad={false}>
          <ul className="divide-y divide-ink-100">
            {activity.map((a) => (
              <li key={a.id} className="px-5 py-2.5">
                <div className="text-sm text-ink-800">{a.title}</div>
                <div className="text-[11px] text-ink-400">{a.category} · {a.actorName ?? a.actorType.toLowerCase()} · {timeAgo(a.createdAt)}</div>
              </li>
            ))}
          </ul>
        </Card>
      </div>
    </div>
  );
}
